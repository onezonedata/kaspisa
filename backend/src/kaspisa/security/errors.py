"""Ошибки пакета security. Тексты не содержат ключей, шифртекстов и открытых значений."""


class KeyConfigError(Exception):
    """Ключ не задан или записан неверно. Текст не содержит значения переменной."""


class DecryptionError(Exception):
    """Неверный ключ, подмена, чужой контекст или битый формат; без подробностей."""


class UnknownKeyError(DecryptionError):
    """В связке нет ключа с идентификатором из блока."""
